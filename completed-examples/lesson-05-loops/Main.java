public class Main {
    public static void main(String[] args) {
        for (int number = 1; number <= 5; number++) {
            System.out.println("Numero: " + number);
        }

        int attempt = 1;

        while (attempt <= 3) {
            System.out.println("Practica numero " + attempt);
            attempt++;
        }
    }
}
